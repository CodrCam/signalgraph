def compact_headings(body):
    def replace(match):
        text = ' '.join(unescape(re.sub('<[^>]+>', ' ', match[2])).split())
        label = HEADINGS.get(text)
        if label is None and ' · reported compensation' in text:
            label = 'Reported Compensation'
        return match[1] + escape(label) + match[3] if label else match[0]
    return re.sub(r'(<h[123]\b[^>]*>)(.*?)(</h[123]>)', replace, body, flags=re.S)
